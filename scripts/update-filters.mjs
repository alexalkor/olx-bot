// Rebuilds cloudflare/lib/filters-data.js from OLX's filter catalog.
// OLX blocks cloud sandboxes, so fetch the catalog through the Worker first:
//   curl -s -G "$WORKER/admin/olx-get" --data-urlencode "path=/api/v1/offers/metadata/filters/" \
//     --data-urlencode max=3000000 | node -e "process.stdout.write(JSON.parse(require('fs').readFileSync(0)).body)" > catalog.json
//   node scripts/update-filters.mjs catalog.json
// ponytail: bundled snapshot, because parsing the 1.5 MB live catalog costs ~10 ms CPU per
// request (the free-plan limit). Re-run when OLX adds categories/filters.
import { readFileSync, writeFileSync } from "node:fs";

const SKIP = new Set(["sort_by", "filter_float_price", "filter_enum_price", "filter_enum_vin"]);
const KIND = { select: "enum", checkboxes: "enum", input: "range", checkbox: "bool" };

const { data } = JSON.parse(readFileSync(process.argv[2], "utf8"));
const out = {};
for (const [key, variants] of Object.entries(data)) {
  if (SKIP.has(key)) continue;
  const list = variants
    .filter((f) => KIND[f.type])
    .map((f) => ({
      k: KIND[f.type],
      l: f.label,
      ...(f.unit ? { u: f.unit } : {}),
      ...(f.values.length ? { v: f.values.map((v) => [v.value, v.label]) } : {}),
      o: (f.options[0] || {}).orderForSearch ?? 999,
      c: [...new Set(f.options.flatMap((o) => o.categories))],
    }))
    .filter((f) => f.k !== "enum" || f.v);
  if (list.length) out[key] = list;
}
const file = new URL("../cloudflare/lib/filters-data.js", import.meta.url);
writeFileSync(file, `// Generated by scripts/update-filters.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit.\nexport default ${JSON.stringify(out)};\n`);
console.log(`${Object.keys(out).length} filters written`);
